def main():
    print("=" * 70)
    print(f"GSC Multi-Period Comparison Agent — {PROPERTY_HOST}")
    print("=" * 70)

    # 1) Authenticate
    print("\nAuthenticating …")
    try:
        account = authenticate()
        print("  Auth OK")
    except Exception as exc:
        print(f"  Auth failed: {exc}")
        sys.exit(1)

    try:
        webproperty = account[PROPERTY_URL]
    except KeyError:
        print(f"Property '{PROPERTY_URL}' not found. Available: {list(account)}")
        sys.exit(1)

    # 2) Fetch all periods
    print("\nFetching data from Search Console …")
    period_dfs = {}
    for label, days_back in PERIODS:
        try:
            period_dfs[label] = fetch_period(webproperty, days_back, label)
        except Exception as exc:
            print(f"  [{label}] Fetch failed: {exc}")
            period_dfs[label] = pd.DataFrame(
                columns=["page", "clicks", "impressions", "ctr", "position"]
            )

    # 3) Merge into wide table
    print("\nMerging periods …")
    period_labels = [label for label, _ in PERIODS]   # ["3m", "6m", "12m"]
    wide = build_wide_table(period_dfs)
    print(f"  {len(wide):,} unique URLs across all periods")

    # 4) Trend pattern
    wide["trend_pattern"] = wide.apply(
        lambda row: label_trend(row, period_labels), axis=1
    )

    # 5) High-click flag  (any period >= threshold)
    click_cols = [f"clicks_{p}" for p in period_labels]
    wide["max_clicks_any_period"] = wide[click_cols].max(axis=1)
    wide["high_click_url"] = wide["max_clicks_any_period"] >= HIGH_CLICK_THRESHOLD
    wide["min_position_any_period"] = wide.apply(
        lambda row: min_position_across_periods(row, period_labels), axis=1
    )
    wide["position_ok"] = wide["min_position_any_period"] >= POSITION_THRESHOLD

    # 6) Enrich with publish age
    print("\nEnriching with publish dates …")
    wide = enrich_publish_age(wide)

    # 7) Column order for wide/all table
    ordered_cols = ["page"]
    for p in period_labels:
        ordered_cols += [f"clicks_{p}", f"impressions_{p}", f"ctr_{p}", f"position_{p}"]
    ordered_cols += [
        "trend_pattern",
        "max_clicks_any_period",
        "high_click_url",
        "min_position_any_period",
        "position_ok",
        "days_since_published",
    ]
    # Keep any extra columns that might exist
    extra = [c for c in wide.columns if c not in ordered_cols]
    wide = wide[ordered_cols + extra]

    # 8) Save CSV 1 — all URLs with all periods
    os.makedirs(CSV_FOLDER, exist_ok=True)
    all_path = os.path.join(CSV_FOLDER, "comparison_all_periods.csv")
    wide.sort_values("days_since_published", ascending=False, na_position="last", inplace=True)
    wide.to_csv(all_path, index=False)
    print(f"\nSaved: {all_path}  ({len(wide):,} rows)")

    # 9) Filter to optimization candidates
    # Anchor on 12m CTR band; exclude high-click; keep only URLs that appear
    # in the 12m data so we have a stable anchor
    anchor = "12m"
    ctr_anchor = f"ctr_{anchor}"
    clicks_anchor = f"clicks_{anchor}"

    candidates = wide.copy()

    # Must exist in anchor period
    candidates = candidates[candidates[ctr_anchor].notna()]

    # CTR band in anchor period
    candidates = candidates[
        (candidates[ctr_anchor] >= CTR_THRESHOLD) &
        (candidates[ctr_anchor] <= CTR_MAX_THRESHOLD)
    ]

    # Exclude high-click URLs
    before_hc = len(candidates)
    candidates = candidates[~candidates["high_click_url"]]
    hc_removed = before_hc - len(candidates)

    # Exclude URLs that rank too well in any available period
    before_pos = len(candidates)
    candidates = candidates[candidates["position_ok"]]
    pos_removed = before_pos - len(candidates)

    print(f"\nCandidates filter:")
    print(f"  CTR {CTR_THRESHOLD:.0%}–{CTR_MAX_THRESHOLD:.0%} in {anchor} window → {before_hc:,} URLs")
    print(f"  Removed {hc_removed:,} high-click URLs (>= {HIGH_CLICK_THRESHOLD} clicks in any period)")
    print(f"  Removed {pos_removed:,} URLs with position < {POSITION_THRESHOLD} in any available period")
    print(f"  Final candidates: {len(candidates):,} URLs")

    # Recommend the next optimization strategy for each candidate.
    print("\n  Generating recommended actions …")
    recommendation_series = candidates.apply(
        lambda row: recommend_action_info(row, period_labels), axis=1
    )
    candidates[RECOMMENDED_ACTION_REASON_COLUMN] = recommendation_series.apply(
        lambda item: item.get("reason", "") if isinstance(item, dict) else ""
    )
    candidates[RECOMMENDED_ACTION_COLUMN] = recommendation_series.apply(
        lambda item: item.get("code", RECOMMENDED_ACTION_CONTENT_PLUS_META)
        if isinstance(item, dict)
        else RECOMMENDED_ACTION_CONTENT_PLUS_META
    )

    # Keep the structured recommendation as the last column for readability in Excel.
    candidate_cols = [
        c for c in candidates.columns
        if c not in {RECOMMENDED_ACTION_COLUMN, RECOMMENDED_ACTION_REASON_COLUMN}
    ]
    candidates = candidates[
        candidate_cols + [RECOMMENDED_ACTION_REASON_COLUMN, RECOMMENDED_ACTION_COLUMN]
    ]

    # Pattern breakdown
    print("\n  Trend pattern breakdown:")
    for pattern, count in candidates["trend_pattern"].value_counts().items():
        print(f"    {pattern:<22} {count:>5}")

    candidate_csv_stem = derive_candidate_csv_stem(PROPERTY_URL)
    cand_path = os.path.join(CSV_FOLDER, f"{candidate_csv_stem}.csv")
    candidates.to_csv(cand_path, index=False)
    print(f"\nSaved: {cand_path}  ({len(candidates):,} rows)")

    # 10) Upload to Google Sheets using the full CSV payload.
    print("\nUploading candidate CSV to Google Sheets …")
    upload_rows = [clean_row_record(record) for record in candidates.to_dict(orient="records")]
    upload_success = True
    final_upload_result = None
    if upload_rows:
        total_chunks = (len(upload_rows) - 1) // UPLOAD_CHUNK_SIZE + 1
        for i in range(0, len(upload_rows), UPLOAD_CHUNK_SIZE):
            chunk = upload_rows[i : i + UPLOAD_CHUNK_SIZE]
            chunk_num = i // UPLOAD_CHUNK_SIZE + 1
            print(f"  Upload chunk {chunk_num}/{total_chunks} ({len(chunk):,} rows)")
            chunk_ok, result = send_to_google_sheets(chunk, is_first_chunk=(i == 0))
            if not chunk_ok:
                upload_success = False
                break
            final_upload_result = result
    else:
        print("  No candidate rows to upload.")

    # 11) Summary
    print("\n" + "=" * 70)
    print("Done.")
    print(f"  {all_path}  — full picture, all URLs, all periods")
    print(f"  {cand_path} — filtered optimization candidates with trend labels")
    if upload_rows:
        if upload_success:
            print(f"  Uploaded {len(upload_rows):,} rows to {SHEET_NAME}")
            if final_upload_result and "spreadsheet_url" in final_upload_result:
                print(f"  Sheet URL: {final_upload_result['spreadsheet_url']}")
        else:
            print("  Upload failed partway through.")
    print("=" * 70)


if __name__ == "__main__":
    main()

def derive_candidate_csv_stem(property_url: str) -> str:
    """Derive the candidate CSV stem from the blog property or override."""
    exact_stem = os.getenv("GSC_CANDIDATE_FILE_STEM")
    if exact_stem:
        return exact_stem.strip().lower().replace(" ", "_")

    override = os.getenv("BLOG_BRAND")
    if override:
        return override.strip().lower().replace("-", "_").replace(" ", "_")

    stem_override = os.getenv("GSC_CANDIDATE_STEM")
    if stem_override:
        return stem_override.strip().lower().replace("-", "_").replace(" ", "_")

    parsed = urlparse(property_url)
    host = (parsed.netloc or parsed.path or property_url or "").lower()
    host = host.split(":", 1)[0]
    if host.startswith("www."):
        host = host[4:]
    if host.startswith("blog."):
        host = host[5:]

    brand = host.split(".", 1)[0] if host else "aspose"
    brand = brand.strip().lower().replace("-", "_")
    return brand or "aspose"


def clean_row_record(record: dict) -> dict:
    """Convert pandas/numpy values into JSON-safe primitives."""
    cleaned = {}
    for key, value in record.items():
        if pd.isna(value):
            cleaned[key] = None
            continue
        if isinstance(value, pd.Timestamp):
            cleaned[key] = value.isoformat()
            continue
        if hasattr(value, "item"):
            try:
                value = value.item()
            except Exception:
                pass
        cleaned[key] = value
    return cleaned


def send_to_google_sheets(rows, is_first_chunk=True):
    """Send rows to the Apps Script receiver."""
    if not WEB_APP_URL:
        print("  Upload failed: GSC_WEB_APP_URL is not set")
        return False, None
    if not SPREADSHEET_ID:
        print("  Upload failed: GSC_SPREADSHEET_ID is not set")
        return False, None
    if not WEB_APP_SHARED_SECRET:
        print("  Upload failed: GSC_WEB_APP_SECRET (or APPS_SCRIPT_SHARED_SECRET) is not set")
        return False, None

    payload = {
        "action": "import_data",
        "spreadsheetId": SPREADSHEET_ID,
        "sheetName": SHEET_NAME,
        "rows": rows,
        "clearExisting": is_first_chunk,
        "shared_secret": WEB_APP_SHARED_SECRET,
        "token": WEB_APP_SHARED_SECRET,
    }

    try:
        response = requests.post(
            WEB_APP_URL,
            headers={"Content-Type": "application/json"},
            data=json.dumps(payload),
            timeout=60,
        )
    except requests.exceptions.Timeout:
        print("  Upload timed out")
        return False, None
    except Exception as exc:
        print(f"  Upload failed: {exc}")
        return False, None

    if response.status_code != 200:
        print(f"  Upload HTTP error {response.status_code}: {response.text[:200]}")
        return False, None

    result = response.json()
    if not result.get("success"):
        print(f"  Upload error: {result.get('error', 'unknown error')}")
        return False, result

    print(f"  Upload ok: {result.get('message')}")
    print(f"  Total rows now in sheet: {result.get('total_rows_in_sheet', 0)}")
    return True, result



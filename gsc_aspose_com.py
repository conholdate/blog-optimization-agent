def authenticate():
    """Authenticate with Google Search Console."""
    if os.path.exists("credentials.json"):
        account = searchconsole.authenticate(credentials="credentials.json")
    else:
        account = searchconsole.authenticate(client_config="client_secret.json")
        account.serialize_credentials("credentials.json")
    return account


def fetch_period(webproperty, days_back: int, label: str) -> pd.DataFrame:
    """Fetch page-level GSC data for a rolling window of *days_back* days."""
    end_date   = datetime.now().date()
    start_date = end_date - timedelta(days=days_back)
    print(f"  [{label}] Fetching {start_date} → {end_date} …", end=" ", flush=True)

    report = webproperty.query.range(start_date, end_date).dimension("page").get()
    df = pd.DataFrame(report)
    print(f"{len(df):,} rows")

    if df.empty:
        return pd.DataFrame(columns=["page", "clicks", "impressions", "ctr", "position"])

    if "ctr" not in df.columns:
        df["ctr"] = df["clicks"] / df["impressions"].replace(0, 1)

    # Keep only the target property and English URLs
    df = df[df["page"].str.contains(PROPERTY_HOST, na=False)]
    df = df[~df["page"].apply(has_language_prefix)]

    return df[["page", "clicks", "impressions", "ctr", "position"]].copy()


def label_trend(row, period_labels):
    """
    Assign a trend pattern based on CTR across available periods.
    Periods are ordered shortest → longest: 3m, 6m, 12m.
    """
    ctr_cols = [f"ctr_{p}" for p in period_labels]
    ctrs = [row.get(c) for c in ctr_cols]
    available = [(p, v) for p, v in zip(period_labels, ctrs) if pd.notna(v)]

    if len(available) < 2:
        return "insufficient_data"

    values = [v for _, v in available]

    # Continuously good / bad (all available periods)
    if all(v >= CTR_GOOD_THRESHOLD for v in values):
        return "continuously_good"
    if all(v < CTR_BAD_THRESHOLD for v in values):
        return "continuously_bad"

    # Improving: shorter window CTR > longer window CTR
    # available[0] = most recent short window, available[-1] = oldest long window
    if all(values[i] > values[i + 1] for i in range(len(values) - 1)):
        return "improving"

    # Declining
    if all(values[i] < values[i + 1] for i in range(len(values) - 1)):
        return "declining"

    return "volatile"


def min_position_across_periods(row, period_labels):
    """Return the best ranking position observed across available periods."""
    position_cols = [f"position_{p}" for p in period_labels]
    positions = pd.to_numeric([row.get(c) for c in position_cols], errors="coerce")
    valid_positions = positions[~pd.isna(positions)]
    if len(valid_positions) == 0:
        return float("nan")
    return float(valid_positions.min())


def build_recommendation_signature(row, period_labels):
    """Build a stable signature for caching LLM recommendations."""
    key_fields = []
    for label in period_labels:
        key_fields.extend([
            f"{label}:{row.get(f'clicks_{label}', '')}",
            f"{label}:{row.get(f'impressions_{label}', '')}",
            f"{label}:{row.get(f'ctr_{label}', '')}",
            f"{label}:{row.get(f'position_{label}', '')}",
        ])
    key_fields.extend([
        f"trend:{row.get('trend_pattern', '')}",
        f"minpos:{row.get('min_position_any_period', '')}",
        f"days:{row.get('days_since_published', '')}",
    ])
    return "|".join(map(str, key_fields))


def normalize_recommended_action_code(action_text: str) -> str | None:
    """Normalize free-form LLM output into one of the structured action codes."""
    if not action_text:
        return None

    text = " ".join(str(action_text).strip().split())
    upper = text.upper()
    compact = re.sub(r"[^A-Z0-9]+", "_", upper).strip("_")
    if compact in RECOMMENDED_ACTION_CODES:
        return compact

    lowered = text.lower()
    if "content refresh + title/meta refresh" in lowered:
        return RECOMMENDED_ACTION_CONTENT_PLUS_META
    if "title/meta refresh" in lowered:
        return RECOMMENDED_ACTION_TITLE_META
    if "full content refresh" in lowered:
        return RECOMMENDED_ACTION_FULL_REFRESH

    return None


def fallback_recommended_action(row) -> dict:
    """Deterministic recommendation used when the LLM is unavailable."""
    position = pd.to_numeric(row.get("min_position_any_period"), errors="coerce")
    ctr = pd.to_numeric(row.get("ctr_12m"), errors="coerce")
    trend = str(row.get("trend_pattern", "volatile")).strip().lower()

    if pd.isna(position):
        position = pd.to_numeric(row.get("position_12m"), errors="coerce")

    if pd.isna(position):
        position = 99.0
    if pd.isna(ctr):
        ctr = 0.0

    if position >= 30:
        return {
            "code": RECOMMENDED_ACTION_FULL_REFRESH,
            "reason": "ranking is deep in search results",
        }

    if trend in {"volatile", "declining"}:
        if position >= 20:
            return {
                "code": RECOMMENDED_ACTION_FULL_REFRESH,
                "reason": "volatile or declining trend with weak second-page ranking",
            }
        return {
            "code": RECOMMENDED_ACTION_TITLE_META,
            "reason": "borderline second-page ranking with unstable trend",
        }

    if trend in {"improving", "continuously_good"}:
        if ctr >= 0.025:
            return {
                "code": RECOMMENDED_ACTION_TITLE_META,
                "reason": "healthy trend with acceptable CTR",
            }
        return {
            "code": RECOMMENDED_ACTION_CONTENT_PLUS_META,
            "reason": "improving page needs content and snippet refresh",
        }

    return {
        "code": RECOMMENDED_ACTION_CONTENT_PLUS_META,
        "reason": "balanced refresh needed for content and snippet",
    }


def clean_recommendation_reason(reason: str) -> str:
    """Normalize recommendation text to a short, compact phrase."""
    text = " ".join(str(reason).strip().split())
    text = re.sub(r"^reason:\s*", "", text, flags=re.IGNORECASE)
    text = text.rstrip(".")
    for separator in (";", ",", ". "):
        if separator in text:
            text = text.split(separator, 1)[0].strip()
            break
    words = text.split()
    if len(words) > MAX_REASON_WORDS:
        text = " ".join(words[:MAX_REASON_WORDS])
    return text


def parse_recommendation_response(raw_text: str) -> dict | None:
    """Parse the LLM response into the structured cell value we want to store."""
    if not raw_text:
        return None

    text = raw_text.strip()
    if text.startswith("```"):
        text = text.strip("`").strip()

    try:
        parsed = json.loads(text)
        if isinstance(parsed, dict):
            action = str(
                parsed.get("recommended_action_code")
                or parsed.get("recommended_action")
                or parsed.get("action")
                or ""
            ).strip()
            reason = str(parsed.get("reason", "")).strip()
            code = normalize_recommended_action_code(action)
            if code:
                return {
                    "code": code,
                    "reason": clean_recommendation_reason(reason) if reason else "",
                }
    except json.JSONDecodeError:
        pass

    if "|" in text:
        action, reason = text.split("|", 1)
        code = normalize_recommended_action_code(action)
        reason = clean_recommendation_reason(reason)
        if code:
            return {"code": code, "reason": reason}

    code = normalize_recommended_action_code(text)
    if code:
        return {"code": code, "reason": ""}

    reason = clean_recommendation_reason(text)
    if reason:
        return {"code": RECOMMENDED_ACTION_CONTENT_PLUS_META, "reason": reason}

    return None


_recommendation_cache = {}


def recommend_action_info(row, period_labels, client=None, allow_llm: bool = True) -> dict:
    """Generate a structured action recommendation using LLM when available."""
    signature = build_recommendation_signature(row, period_labels)
    if signature in _recommendation_cache:
        return _recommendation_cache[signature]

    position = row.get("min_position_any_period", "")
    ctr_12m = row.get("ctr_12m", "")
    clicks_12m = row.get("clicks_12m", "")
    impressions_12m = row.get("impressions_12m", "")
    trend = row.get("trend_pattern", "")
    days_since_published = row.get("days_since_published", "")

    fallback = fallback_recommended_action(row)
    if not allow_llm:
        _recommendation_cache[signature] = fallback
        return fallback

    client = client or RECOMMENDATION_CLIENT
    if client is None:
        _recommendation_cache[signature] = fallback
        return fallback

    prompt = f"""
You are recommending the next optimization strategy for a blog post.
Return only JSON with keys:
- recommended_action_code
- reason

The action code must be one of:
- {RECOMMENDED_ACTION_TITLE_META}
- {RECOMMENDED_ACTION_FULL_REFRESH}
- {RECOMMENDED_ACTION_CONTENT_PLUS_META}

The reason must be a short fragment of at most {MAX_REASON_WORDS} words.
Do not include the word "Reason:" in the value.

Use the metrics below to decide.
URL: {row.get('page', '')}
Clicks (12m): {clicks_12m}
Impressions (12m): {impressions_12m}
CTR (12m): {ctr_12m}
Position (best across periods): {position}
Trend pattern: {trend}
Days since published: {days_since_published}

Guidance:
- Use {RECOMMENDED_ACTION_TITLE_META} when the page is near the second-page boundary and mostly needs a better snippet.
- Use {RECOMMENDED_ACTION_FULL_REFRESH} when trend is volatile or declining, or the page is far beyond page one.
- Use {RECOMMENDED_ACTION_CONTENT_PLUS_META} when both content and metadata should be refreshed.
- Keep the reason short: a fragment, not a sentence.

Example:
{{"recommended_action_code":"{RECOMMENDED_ACTION_TITLE_META}","reason":"borderline second-page ranking with unstable trend"}}
{{"recommended_action_code":"{RECOMMENDED_ACTION_FULL_REFRESH}","reason":"volatile or declining trend with weak second-page ranking"}}
""".strip()

    try:
        response = client.chat.completions.create(
            model=LLM_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": "You are a strict blog optimization strategist. Return JSON only.",
                },
                {"role": "user", "content": prompt},
            ],
            temperature=0.2,
            max_tokens=120,
            timeout=20.0,
        )
        raw_text = (response.choices[0].message.content or "").strip()
        recommendation = parse_recommendation_response(raw_text)
        if recommendation:
            _recommendation_cache[signature] = recommendation
            return recommendation
    except Exception as exc:
        print(f"  Warning: recommendation LLM failed for {row.get('page', '')}: {exc}")

    _recommendation_cache[signature] = fallback
    return fallback


def recommend_action(row, period_labels, client=None, allow_llm: bool = True) -> str:
    """Backward-compatible wrapper that returns only the action code."""
    return recommend_action_info(row, period_labels, client=client, allow_llm=allow_llm)["code"]


def build_wide_table(period_dfs: dict) -> pd.DataFrame:
    """
    Merge per-period DataFrames into a single wide table keyed on 'page'.
    Suffix each metric column with the period label.
    """
    merged = None
    for label, df in period_dfs.items():
        renamed = df.rename(columns={
            "clicks":      f"clicks_{label}",
            "impressions": f"impressions_{label}",
            "ctr":         f"ctr_{label}",
            "position":    f"position_{label}",
        })
        if merged is None:
            merged = renamed
        else:
            merged = merged.merge(renamed, on="page", how="outer")

    return merged.reset_index(drop=True)


def enrich_publish_age(df: pd.DataFrame) -> pd.DataFrame:
    """Add 'days_since_published' column via local content repo, if available."""
    content_root, days_map, parsed, matched, total, _ = select_best_days_since_map(
        CONTENT_REPO_NAME, df["page"].tolist()
    )
    if content_root:
        print(f"  Content root: {content_root}")
        print(f"  Indexed {parsed:,} posts; matched {matched:,}/{total:,} URLs")
    else:
        print("  Content root not found — skipping publish-age enrichment.")
        days_map = {}

    df["days_since_published"] = df["page"].apply(
        lambda p: days_map.get(url_to_path(str(p)))
    )
    return df


